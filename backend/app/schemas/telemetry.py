"""
Enhanced Telemetry Packet and Event Schemas.
Every telemetry packet generated by the simulation engine includes:
- source: "simulated"
- 10-bit quantized ADC readings
- Digital sensor states
- Warm-up and device health indicators
- Local simulated risk tier and event list
"""

from datetime import datetime
from typing import Optional, List, Literal, Dict, Any
from pydantic import BaseModel, Field


class BME280Readings(BaseModel):
    temperature_c: float = Field(..., description="Ambient temperature in °C")
    humidity_pct: float = Field(..., description="Relative humidity in %")
    pressure_hpa: float = Field(..., description="Atmospheric pressure in hPa")


class GasSensorDetails(BaseModel):
    raw_adc: int = Field(..., ge=0, le=1023, description="10-bit raw ADC reading (0-1023)")
    voltage_v: float = Field(..., ge=0.0, le=5.5, description="Analog pin voltage (0-5V)")
    normalized_ratio: float = Field(..., ge=0.0, le=1.0, description="Normalized sensor output ratio")
    is_warmed_up: bool = Field(True, description="Whether heater coil reached operating temperature")


class SensorReadings(BaseModel):
    bme280: BME280Readings
    mq2_raw: int = Field(..., ge=0, le=1023, description="10-bit raw ADC reading (0-1023)")
    mq7_raw: int = Field(..., ge=0, le=1023, description="10-bit raw ADC reading (0-1023)")
    mq135_raw: int = Field(..., ge=0, le=1023, description="10-bit raw ADC reading (0-1023)")
    ir_state: int = Field(..., ge=0, le=1, description="Digital beam break: 0=clear, 1=broken")
    battery_voltage_v: float = Field(5.0, ge=0.0, le=5.5, description="Supply/battery voltage in V")
    # Extended diagnostic channels
    mq2_details: Optional[GasSensorDetails] = None
    mq7_details: Optional[GasSensorDetails] = None
    mq135_details: Optional[GasSensorDetails] = None


class DeviceHealth(BaseModel):
    is_connected: bool = True
    health_status: Literal["HEALTHY", "DEGRADED", "CRITICAL_FAULT"] = "HEALTHY"
    uptime_sec: float = 0.0
    all_warmed_up: bool = False


class TelemetryPacket(BaseModel):
    schema_version: str = "1.1.0"
    packet_id: str
    session_id: str
    device_id: str
    sequence_number: int
    timestamp: datetime
    source: Literal["simulated"] = "simulated"
    scenario_id: str = "scenario-01"
    sim_time_sec: float = 0.0
    readings: SensorReadings
    device_health: Optional[DeviceHealth] = None
    simulated_tier: str = "GREEN"  # "GREEN", "YELLOW", "ORANGE", "RED", "FAULT"
    active_events: Optional[List[Dict[str, Any]]] = None


class WebSocketEvent(BaseModel):
    event_type: str
    session_id: str
    timestamp: datetime
    payload: dict
