"""
Local Simulation Event Processor.
Evaluates simulated telemetry readings against configurable demonstration thresholds
and generates local, educational simulated warning events and risk tier classifications.

IMPORTANT REGULATORY & MEDICAL DISCLAIMER:
These evaluated events are strictly LOCAL DEMONSTRATION SIGNALS generated by the simulator.
They are NOT clinical medical diagnoses, certified industrial hygiene classifications,
or verified emergency hazard determinations.
"""

import uuid
from datetime import datetime, timezone
from typing import List, Dict, Any, Optional
from pydantic import BaseModel, Field


class SimulatedLocalEvent(BaseModel):
    event_id: str = Field(default_factory=lambda: f"EVT-{uuid.uuid4().hex[:8].upper()}")
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    sim_time_sec: float
    severity: str  # "INFO", "WARNING", "HIGH", "CRITICAL"
    event_category: str  # "THERMAL", "SMOKE", "TOXIC_GAS", "AIR_QUALITY", "HARDWARE_FAULT"
    triggering_sensor: str
    observed_value: float
    threshold_value: float
    human_explanation: str
    source: str = "simulated"


class RiskTierResult(BaseModel):
    tier: str  # "GREEN", "YELLOW", "ORANGE", "RED", "FAULT"
    confidence: float = 1.0
    active_events: List[SimulatedLocalEvent] = Field(default_factory=list)
    primary_threat: Optional[str] = None


class LocalEventProcessor:
    """
    Evaluates current simulated telemetry data points against threshold boundaries.
    Generates structured SimulatedLocalEvent objects and computes the simulated risk tier.
    """

    def __init__(self):
        # Demonstration thresholds (tunable for education and hackathon evaluation)
        self.thresholds = {
            "temp_yellow_c": 32.0,
            "temp_orange_c": 38.0,
            "temp_red_c": 42.0,
            "humidity_high_pct": 80.0,
            "mq2_warning_adc": 350,
            "mq2_critical_adc": 650,
            "mq7_warning_adc": 250,
            "mq7_critical_adc": 600,
            "mq135_warning_adc": 320,
            "mq135_critical_adc": 580,
        }

    def evaluate(
        self,
        sim_time_sec: float,
        temperature_c: float,
        humidity_pct: float,
        pressure_hpa: float,
        mq2_raw: int,
        mq7_raw: int,
        mq135_raw: int,
        ir_state: int,
    ) -> RiskTierResult:
        events: List[SimulatedLocalEvent] = []

        # 1. Hardware Fault Checks
        if temperature_c <= -900.0 or humidity_pct <= -900.0:
            events.append(
                SimulatedLocalEvent(
                    sim_time_sec=sim_time_sec,
                    severity="CRITICAL",
                    event_category="HARDWARE_FAULT",
                    triggering_sensor="BME280",
                    observed_value=temperature_c,
                    threshold_value=-900.0,
                    human_explanation="I2C bus dropout detected on environmental sensor BME280. Telemetry line invalid.",
                )
            )
            return RiskTierResult(tier="FAULT", active_events=events, primary_threat="BME280 I2C Bus Fault")

        if mq7_raw >= 1020:
            events.append(
                SimulatedLocalEvent(
                    sim_time_sec=sim_time_sec,
                    severity="CRITICAL",
                    event_category="HARDWARE_FAULT",
                    triggering_sensor="MQ-7",
                    observed_value=float(mq7_raw),
                    threshold_value=1020.0,
                    human_explanation="MQ-7 ADC railed to 1023. Possible open-circuit pull-up or wire disconnection.",
                )
            )
            return RiskTierResult(tier="FAULT", active_events=events, primary_threat="MQ-7 Analog Line Disconnection")

        # 2. Thermal / Heat Stress Evaluation
        if temperature_c >= self.thresholds["temp_red_c"]:
            events.append(
                SimulatedLocalEvent(
                    sim_time_sec=sim_time_sec,
                    severity="CRITICAL",
                    event_category="THERMAL",
                    triggering_sensor="BME280",
                    observed_value=temperature_c,
                    threshold_value=self.thresholds["temp_red_c"],
                    human_explanation=f"Extreme ambient temperature ({temperature_c:.1f}°C) exceeds safe operational threshold (42.0°C).",
                )
            )
        elif temperature_c >= self.thresholds["temp_orange_c"]:
            events.append(
                SimulatedLocalEvent(
                    sim_time_sec=sim_time_sec,
                    severity="HIGH",
                    event_category="THERMAL",
                    triggering_sensor="BME280",
                    observed_value=temperature_c,
                    threshold_value=self.thresholds["temp_orange_c"],
                    human_explanation=f"Elevated ambient temperature ({temperature_c:.1f}°C) indicates severe thermal strain.",
                )
            )
        elif temperature_c >= self.thresholds["temp_yellow_c"]:
            events.append(
                SimulatedLocalEvent(
                    sim_time_sec=sim_time_sec,
                    severity="WARNING",
                    event_category="THERMAL",
                    triggering_sensor="BME280",
                    observed_value=temperature_c,
                    threshold_value=self.thresholds["temp_yellow_c"],
                    human_explanation=f"Ambient temperature ({temperature_c:.1f}°C) reached advisory threshold (32.0°C).",
                )
            )

        # 3. High Humidity / Humid Heat Wet-Bulb Stress
        if temperature_c >= 33.0 and humidity_pct >= self.thresholds["humidity_high_pct"]:
            events.append(
                SimulatedLocalEvent(
                    sim_time_sec=sim_time_sec,
                    severity="CRITICAL",
                    event_category="THERMAL",
                    triggering_sensor="BME280",
                    observed_value=humidity_pct,
                    threshold_value=self.thresholds["humidity_high_pct"],
                    human_explanation=f"Dangerous combined humid heat ({temperature_c:.1f}°C at {humidity_pct:.1f}% RH). Evaporative heat rejection impaired.",
                )
            )

        # 4. MQ-7 Carbon Monoxide Response
        if mq7_raw >= self.thresholds["mq7_critical_adc"]:
            events.append(
                SimulatedLocalEvent(
                    sim_time_sec=sim_time_sec,
                    severity="CRITICAL",
                    event_category="TOXIC_GAS",
                    triggering_sensor="MQ-7",
                    observed_value=float(mq7_raw),
                    threshold_value=float(self.thresholds["mq7_critical_adc"]),
                    human_explanation=f"Critical Carbon Monoxide response ({mq7_raw} ADC counts). Potential severe exposure hazard.",
                )
            )
        elif mq7_raw >= self.thresholds["mq7_warning_adc"]:
            events.append(
                SimulatedLocalEvent(
                    sim_time_sec=sim_time_sec,
                    severity="WARNING",
                    event_category="TOXIC_GAS",
                    triggering_sensor="MQ-7",
                    observed_value=float(mq7_raw),
                    threshold_value=float(self.thresholds["mq7_warning_adc"]),
                    human_explanation=f"Elevated Carbon Monoxide response ({mq7_raw} ADC counts). Advisory notice.",
                )
            )

        # 5. MQ-2 Smoke and Combustible Gas Response
        if mq2_raw >= self.thresholds["mq2_critical_adc"]:
            events.append(
                SimulatedLocalEvent(
                    sim_time_sec=sim_time_sec,
                    severity="CRITICAL",
                    event_category="SMOKE",
                    triggering_sensor="MQ-2",
                    observed_value=float(mq2_raw),
                    threshold_value=float(self.thresholds["mq2_critical_adc"]),
                    human_explanation=f"Dense smoke/hydrocarbon gas signature detected ({mq2_raw} ADC counts). Fire or fuel leak warning.",
                )
            )
        elif mq2_raw >= self.thresholds["mq2_warning_adc"]:
            events.append(
                SimulatedLocalEvent(
                    sim_time_sec=sim_time_sec,
                    severity="WARNING",
                    event_category="SMOKE",
                    triggering_sensor="MQ-2",
                    observed_value=float(mq2_raw),
                    threshold_value=float(self.thresholds["mq2_warning_adc"]),
                    human_explanation=f"Elevated smoke or combustible gas reading ({mq2_raw} ADC counts).",
                )
            )

        # 6. MQ-135 Air Quality Response
        if mq135_raw >= self.thresholds["mq135_critical_adc"]:
            events.append(
                SimulatedLocalEvent(
                    sim_time_sec=sim_time_sec,
                    severity="HIGH",
                    event_category="AIR_QUALITY",
                    triggering_sensor="MQ-135",
                    observed_value=float(mq135_raw),
                    threshold_value=float(self.thresholds["mq135_critical_adc"]),
                    human_explanation=f"Degraded air quality reading ({mq135_raw} ADC counts). Substantial airborne contaminants detected.",
                )
            )

        # 7. Optical IR beam break
        if ir_state == 1:
            events.append(
                SimulatedLocalEvent(
                    sim_time_sec=sim_time_sec,
                    severity="INFO",
                    event_category="OPTICAL",
                    triggering_sensor="IR_SENSOR",
                    observed_value=1.0,
                    threshold_value=1.0,
                    human_explanation="Optical beam broken (provisional: particulate density occlusion or optical barrier interrupt).",
                )
            )

        # 8. Compute Overall Simulated Risk Tier
        has_critical = any(e.severity == "CRITICAL" for e in events)
        has_high = any(e.severity == "HIGH" for e in events)
        has_warning = any(e.severity == "WARNING" for e in events)

        if has_critical:
            tier = "RED"
        elif has_high:
            tier = "ORANGE"
        elif has_warning:
            tier = "YELLOW"
        else:
            tier = "GREEN"

        primary_threat = events[0].human_explanation if events else "Nominal environmental baseline"

        return RiskTierResult(
            tier=tier,
            active_events=events,
            primary_threat=primary_threat,
        )
