import React, { useState } from 'react'
import { SurfacePanel } from '@/components/ui/panels'
import { FileText, Download, ChevronDown, ChevronUp } from 'lucide-react'
import type { TelemetryPacketData } from '@/types/telemetry'

interface SimulationReportExportProps {
  sessionId: string | null
  scenarioId: string
  simTimeSec: number
  history: TelemetryPacketData[]
}

export const SimulationReportExport: React.FC<SimulationReportExportProps> = ({
  sessionId,
  scenarioId,
  simTimeSec,
  history,
}) => {
  const [isOpen, setIsOpen] = useState(false)

  // Compute statistical summaries from captured telemetry
  const stats = React.useMemo(() => {
    if (history.length === 0) return null

    const temps = history.map((p) => p.readings.bme280.temperature_c)
    const hums = history.map((p) => p.readings.bme280.humidity_pct)
    const mq2s = history.map((p) => p.readings.mq2_raw)
    const mq7s = history.map((p) => p.readings.mq7_raw)
    const mq135s = history.map((p) => p.readings.mq135_raw)

    const avg = (arr: number[]) => (arr.reduce((a, b) => a + b, 0) / arr.length).toFixed(1)

    return {
      temp: { min: Math.min(...temps).toFixed(1), max: Math.max(...temps).toFixed(1), avg: avg(temps) },
      hum: { min: Math.min(...hums).toFixed(1), max: Math.max(...hums).toFixed(1), avg: avg(hums) },
      mq2: { min: Math.min(...mq2s), max: Math.max(...mq2s), avg: avg(mq2s) },
      mq7: { min: Math.min(...mq7s), max: Math.max(...mq7s), avg: avg(mq7s) },
      mq135: { min: Math.min(...mq135s), max: Math.max(...mq135s), avg: avg(mq135s) },
    }
  }, [history])

  const handleExportCSV = () => {
    if (history.length === 0) return

    const headers = [
      'sequence_number',
      'sim_time_sec',
      'timestamp',
      'temperature_c',
      'humidity_pct',
      'pressure_hpa',
      'mq2_raw_adc',
      'mq7_raw_adc',
      'mq135_raw_adc',
      'ir_state',
      'battery_voltage_v',
      'simulated_tier',
      'source',
    ]

    const rows = history.map((p) => [
      p.sequence_number,
      p.sim_time_sec,
      p.timestamp,
      p.readings.bme280.temperature_c,
      p.readings.bme280.humidity_pct,
      p.readings.bme280.pressure_hpa,
      p.readings.mq2_raw,
      p.readings.mq7_raw,
      p.readings.mq135_raw,
      p.readings.ir_state,
      p.readings.battery_voltage_v,
      p.simulated_tier,
      p.source,
    ])

    const csvContent = [headers.join(','), ...rows.map((r) => r.join(','))].join('\n')
    const blob = new Blob([csvContent], { type: 'text/csv' })
    const url = URL.createObjectURL(blob)
    const a = document.createElement('a')
    a.href = url
    a.download = `allevia-simulation-report-${sessionId || 'session'}.csv`
    a.click()
    URL.revokeObjectURL(url)
  }

  const handleExportJSON = () => {
    const reportData = {
      export_title: 'ALLEVIA Simulation Telemetry Run Report',
      source: 'simulated',
      disclaimer: 'Generated by ALLEVIA Environment Simulator. Strictly for demonstration and training.',
      session_id: sessionId,
      scenario_id: scenarioId,
      total_packets: history.length,
      elapsed_simulation_sec: simTimeSec,
      statistics: stats,
      telemetry_packets: history,
    }

    const blob = new Blob([JSON.stringify(reportData, null, 2)], { type: 'application/json' })
    const url = URL.createObjectURL(blob)
    const a = document.createElement('a')
    a.href = url
    a.download = `allevia-simulation-report-${sessionId || 'session'}.json`
    a.click()
    URL.revokeObjectURL(url)
  }

  return (
    <SurfacePanel className="border border-[var(--border-subtle)] p-4 rounded-xl">
      <div
        className="flex items-center justify-between cursor-pointer select-none"
        onClick={() => setIsOpen(!isOpen)}
      >
        <div className="flex items-center gap-2.5">
          <FileText className="w-4 h-4 text-[var(--accent-primary)]" />
          <div>
            <h3 className="text-sm font-semibold text-[var(--foreground-default)] flex items-center gap-2">
              Simulation Run Report &amp; Data Export
              <span className="px-1.5 py-0.5 text-[10px] font-mono bg-cyan-500/10 text-[var(--accent-primary)] rounded border border-cyan-500/20">
                CSV / JSON
              </span>
            </h3>
            <p className="text-xs text-[var(--foreground-muted)]">
              Download complete structured telemetry logs and statistical channel summaries.
            </p>
          </div>
        </div>
        {isOpen ? <ChevronUp className="w-4 h-4 text-[var(--foreground-muted)]" /> : <ChevronDown className="w-4 h-4 text-[var(--foreground-muted)]" />}
      </div>

      {isOpen && (
        <div className="mt-4 pt-4 border-t border-[var(--border-subtle)] space-y-3">
          {stats ? (
            <div className="grid grid-cols-2 sm:grid-cols-5 gap-2 text-xs font-mono">
              <div className="p-2 bg-[var(--surface-secondary)] rounded border border-[var(--border-subtle)]">
                <span className="text-[10px] text-[var(--foreground-muted)] block">TEMP (°C)</span>
                <span className="font-bold">{stats.temp.avg}°C</span>
                <span className="text-[10px] block opacity-70">[{stats.temp.min} - {stats.temp.max}]</span>
              </div>
              <div className="p-2 bg-[var(--surface-secondary)] rounded border border-[var(--border-subtle)]">
                <span className="text-[10px] text-[var(--foreground-muted)] block">RH (%)</span>
                <span className="font-bold">{stats.hum.avg}%</span>
                <span className="text-[10px] block opacity-70">[{stats.hum.min} - {stats.hum.max}]</span>
              </div>
              <div className="p-2 bg-[var(--surface-secondary)] rounded border border-[var(--border-subtle)]">
                <span className="text-[10px] text-[var(--foreground-muted)] block">MQ-2 (ADC)</span>
                <span className="font-bold">{stats.mq2.avg}</span>
                <span className="text-[10px] block opacity-70">[{stats.mq2.min} - {stats.mq2.max}]</span>
              </div>
              <div className="p-2 bg-[var(--surface-secondary)] rounded border border-[var(--border-subtle)]">
                <span className="text-[10px] text-[var(--foreground-muted)] block">MQ-7 (ADC)</span>
                <span className="font-bold">{stats.mq7.avg}</span>
                <span className="text-[10px] block opacity-70">[{stats.mq7.min} - {stats.mq7.max}]</span>
              </div>
              <div className="p-2 bg-[var(--surface-secondary)] rounded border border-[var(--border-subtle)]">
                <span className="text-[10px] text-[var(--foreground-muted)] block">MQ-135 (ADC)</span>
                <span className="font-bold">{stats.mq135.avg}</span>
                <span className="text-[10px] block opacity-70">[{stats.mq135.min} - {stats.mq135.max}]</span>
              </div>
            </div>
          ) : (
            <div className="p-3 bg-[var(--surface-secondary)] rounded text-xs font-mono text-[var(--foreground-muted)]">
              No telemetry captured yet for statistical aggregation. Run a simulation to populate report.
            </div>
          )}

          <div className="flex items-center justify-between pt-2">
            <span className="text-[10px] font-mono text-[var(--foreground-subtle)]">
              DISCLAIMER: DATA TAGGED WITH SOURCE='SIMULATED'
            </span>
            <div className="flex items-center gap-2">
              <button
                type="button"
                onClick={handleExportCSV}
                disabled={history.length === 0}
                className="px-3 py-1.5 bg-[var(--surface-secondary)] hover:bg-[var(--surface-hover)] disabled:opacity-50 text-[var(--foreground-default)] rounded border border-[var(--border-subtle)] text-xs font-mono flex items-center gap-1.5 transition-colors"
              >
                <Download className="w-3.5 h-3.5" /> Export CSV ({history.length} rows)
              </button>
              <button
                type="button"
                onClick={handleExportJSON}
                disabled={history.length === 0}
                className="px-3 py-1.5 bg-[var(--surface-secondary)] hover:bg-[var(--surface-hover)] disabled:opacity-50 text-[var(--foreground-default)] rounded border border-[var(--border-subtle)] text-xs font-mono flex items-center gap-1.5 transition-colors"
              >
                <Download className="w-3.5 h-3.5" /> Export JSON
              </button>
            </div>
          </div>
        </div>
      )}
    </SurfacePanel>
  )
}
